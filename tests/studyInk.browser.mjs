import assert from 'node:assert/strict'
import { chromium } from 'playwright'

const origin = process.env.INK_TEST_ORIGIN || 'http://localhost:3000'
const browser = await chromium.launch({ channel: 'msedge' })
try {
  const page = await browser.newPage({ viewport: { width: 1100, height: 750 } })
  page.on('pageerror', error => console.error(error.message))
  await page.goto(new URL('/simulado-priapismo', origin).href, { waitUntil: 'domcontentloaded' })
  const toggle = page.getByRole('button', { name: '✎ Anotar' })
  await toggle.click({ timeout: 90000 })
  await page.mouse.move(12, 220)
  await page.mouse.down()
  await page.mouse.move(110, 255, { steps: 12 })
  await page.mouse.up()
  await page.getByText('Salvo neste dispositivo', { exact: true }).waitFor()
  const stroke = page.locator('svg.fixed polyline').first()
  const points = await stroke.getAttribute('points')
  await page.reload()
  await toggle.waitFor()
  await stroke.waitFor({ state: 'attached' })
  assert.equal(await stroke.getAttribute('points'), points)
  console.log('A escrita na margem foi restaurada após recarregar.')
  await page.goto(new URL('/flashcards', origin).href, {waitUntil: 'domcontentloaded'})
  await page.getByTitle(/^Estudar \d+ cards de /).first().click()
  await toggle.click()
  await page.mouse.move(28, 160)
  await page.mouse.down()
  await page.mouse.move(98, 184, {steps: 15})
  await page.mouse.up()
  await page.getByText('Salvo neste dispositivo', {exact:true}).waitFor()
  const front = await stroke.getAttribute('points')
  await page.getByRole('button',{name:'Virar cartão',exact:true}).click()
  assert.equal(await stroke.getAttribute('points'),front)
  await page.getByRole('button',{name:/^Difícil/}).waitFor()
  await page.getByRole('button',{name:'Virar cartão',exact:true}).click()
  await page.getByRole('button',{name:'Recolher caneta',exact:true}).click()
  await page.getByRole('button',{name:'Próximo card',exact:true}).click()
  await stroke.waitFor({state:'detached'})
  await page.getByRole('button',{name:'Card anterior',exact:true}).click()
  await stroke.waitFor({state:'attached'})
  assert.equal(await stroke.getAttribute('points'),front)
  console.log('Flashcard: mesma anotação na frente e verso, recuperada ao voltar do próximo cartão.')
} finally {
  await browser.close()
}
